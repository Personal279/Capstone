/**
 * The one place the app's mandatory AI-disclosure wording lives, so it stays consistent
 * everywhere a prediction is shown and never drifts into diagnostic-sounding language.
 */
object AiDisclosure {
    const val SHORT = "AI-estimated grade — not a medical diagnosis."
    const val FULL = "This result is generated by an AI model and may be inaccurate. It is not " +
        "a medical diagnosis and does not replace professional care. Please discuss this result " +
        "with a qualified healthcare professional."
}

@Composable
